const n = (p: Params, k = "n") => Number(p[k]);

const plRu = (v: number, one: string, few: string, many: string) => {
  const a = Math.abs(v) % 100;
  const b = a % 10;
  if (b === 1 && a !== 11) return one;
  if (b >= 2 && b <= 4 && (a < 12 || a > 14)) return few;
  return many;
};

const enOrdinal = (v: number) => {
  const t = v % 100;
  if (t >= 11 && t <= 13) return `${v}th`;
  return `${v}${({ 1: "st", 2: "nd", 3: "rd" } as Record<number, string>)[v % 10] ?? "th"}`;
};
const s = (v: number, one: string, many: string) => (v === 1 ? one : many);

